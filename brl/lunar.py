def festival_name(d, ld):
    """返回 (节日名, 是否农历节日)"""
    if (d.month, d.day) in SOLAR_FEST:
        return SOLAR_FEST[(d.month, d.day)], False
    if ld and not ld.leap:
        if (ld.month, ld.day) in LUNAR_FEST:
            return LUNAR_FEST[(ld.month, ld.day)], True
        # 除夕 = 腊月最后一天
        if ld.month == 12 and not ld.leap:
            row = _year_row(ld.year)
            if row:
                lens = [30 if c == "1" else 29 for c in row[4]]
                if ld.day == lens[-1]:
                    return u"除夕", True
    return None, False


