class LunarDate(object):
    __slots__ = ("year", "month", "day", "leap", "solar")

    def __init__(self, year, month, day, leap=False, solar=None):
        self.year = year
        self.month = month
        self.day = day
        self.leap = leap
        self.solar = solar

    @property
    def month_cn(self):
        if self.leap:
            return u"闰" + LUNAR_MONTHS[self.month - 1] + u"月"
        return LUNAR_MONTHS[self.month - 1] + u"月"

    @property
    def day_cn(self):
        return LUNAR_DAYS[self.day - 1]

    def __repr__(self):
        return "LunarDate(%d, %d, %d, leap=%r)" % (self.year, self.month, self.day, self.leap)


def _year_row(lunar_year):
    i = lunar_year - 1900
    if 0 <= i < len(LUNAR_TABLE):
        return LUNAR_TABLE[i]
    return None


def _month_count(row):
    return len(row[4])


def lunar_from_solar(d):
    """公历 date -> LunarDate"""
    for offset in (0, -1, 1):
        ly = d.year + offset
        row = _year_row(ly)
        if row is None:
            continue
        spring = datetime.date(ly, row[1], row[2])
        if spring > d:
            # 农历年尚未开始，属上一个农历年
            if offset == 0:
                continue
        delta = (d - spring).days
        if delta < 0:
            continue
        lens = [30 if c == "1" else 29 for c in row[4]]
        leap = row[3]
        # 构造月序列
        seq = []
        for m in range(1, 13):
            seq.append((m, False))
            if leap == m:
                seq.append((m, True))
        acc = 0
        for idx, (m, lf) in enumerate(seq):
            if idx >= len(lens):
                break
            ln = lens[idx]
            if delta < acc + ln:
                return LunarDate(ly, m, delta - acc + 1, lf, d)
            acc += ln
        # 落在下一年
        continue
    # 退化为使用上一年
    row = _year_row(d.year - 1)
    if row is None:
        return None
    spring = datetime.date(d.year - 1, row[1], row[2])
    delta = (d - spring).days
    lens = [30 if c == "1" else 29 for c in row[4]]
    leap = row[3]
    seq = []
    for m in range(1, 13):
        seq.append((m, False))
        if leap == m:
            seq.append((m, True))
    acc = 0
    for idx, (m, lf) in enumerate(seq):
        if idx >= len(lens):
            break
        ln = lens[idx]
        if delta < acc + ln:
            return LunarDate(d.year - 1, m, delta - acc + 1, lf, d)
        acc += ln
    return None


def solar_from_lunar(year, month, day, leap=False):
    row = _year_row(year)
    if row is None:
        return None
    spring = datetime.date(year, row[1], row[2])
    lens = [30 if c == "1" else 29 for c in row[4]]
    leapm = row[3]
    seq = []
    for m in range(1, 13):
        seq.append((m, False))
        if leapm == m:
            seq.append((m, True))
    idx = 0
    for i, (m, lf) in enumerate(seq):
        if m == month and lf == leap:
            idx = i
            break
    if idx >= len(lens):
        return None
    return spring + datetime.timedelta(days=sum(lens[:idx]) + day - 1)


# ---------------- 节气（Meeus 太阳视黄经） ----------------

def _sun_longitude(jde):
    t = (jde - 2451545.0) / 36525.0
    l0 = 280.46646 + 36000.76983 * t + 0.0003032 * t * t
    m = 357.52911 + 35999.05029 * t - 0.0001537 * t * t
    c = ((1.914602 - 0.004817 * t - 0.000014 * t * t) * _sin(m)
         + (0.019993 - 0.000101 * t) * _sin(2 * m)
         + 0.000289 * _sin(3 * m))
    true_lon = l0 + c
    omega = 125.04 - 1934.136 * t
    app = true_lon - 0.00569 - 0.00478 * _sin(omega)
    return app % 360.0


def _sin(deg):
    import math
    return math.sin(math.radians(deg))


def _cos(deg):
    import math
    return math.cos(math.radians(deg))


TERM_GUESS = [(2, 4), (2, 19), (3, 6), (3, 21), (4, 5), (4, 20), (5, 6), (5, 21),
              (6, 6), (6, 21), (7, 7), (7, 23), (8, 8), (8, 23), (9, 8), (9, 23),
              (10, 8), (10, 23), (11, 7), (11, 22), (12, 7), (12, 22), (1, 6), (1, 20)]


def solar_term_date(year, index):
    """index: 0=立春 ... 21=冬至, 22=小寒, 23=大寒。返回该节气在公历 year 年内的日期。"""
    target = (315 + 15 * index) % 360.0
    gm, gd = TERM_GUESS[index]
    jde = _to_jde(datetime.date(year, gm, gd))
    for _ in range(8):
        lam = _sun_longitude(jde)
        delta = ((target - lam + 540.0) % 360.0) - 180.0
        jde += delta / 0.98565
        if abs(delta) < 1e-7:
            break
    jd_ut = jde - 69.184 / 86400.0
    dt = _from_jde(jd_ut) + datetime.timedelta(hours=8)
    if dt.year != year:
        # 命中相邻年份，向目标年份方向搜索
        for sign in (-1, 1):
            j2 = jde + sign * 365.2422
            for _ in range(8):
                lam = _sun_longitude(j2)
                delta = ((target - lam + 540.0) % 360.0) - 180.0
                j2 += delta / 0.98565
                if abs(delta) < 1e-7:
                    break
            d2 = _from_jde(j2 - 69.184 / 86400.0) + datetime.timedelta(hours=8)
            if d2.year == year:
                return d2.date()
    return dt.date()


_EPOCH = datetime.date(2000, 1, 1)


def _to_jde(d):
    days = (d - _EPOCH).days
    return 2451544.5 + days


def _from_jde(jde):
    import datetime as _dt
    days = jde - 2451544.5
    base = _dt.datetime(2000, 1, 1, 12, 0, 0)
    return base + _dt.timedelta(days=days - 0.5)


def year_terms(year):
    """返回 {公历date: 节气名}，覆盖公历 year 年内出现的全部 24 个节气"""
    out = {}
    # 小寒/大寒出现在 1 月（黄经 285/300），其余从立春开始
    order = [22, 23] + list(range(0, 22))
    for k, idx in enumerate(order):
        d = solar_term_date(year, idx)
        if d.year != year:
            continue
        out[d] = TERM_NAMES[idx]
    return out


